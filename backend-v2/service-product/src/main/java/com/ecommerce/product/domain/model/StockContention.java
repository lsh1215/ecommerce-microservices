package com.ecommerce.product.domain.model;

/**
 * 이 옵션의 재고 차감을 어떤 방식으로 처리할지 결정하는 등급.
 *
 * <p>재고 차감은 결국 "같은 재고를 여러 요청이 동시에 깎는" 문제이고, 어디서 직렬화되느냐가
 * 처리량을 정한다. 경합 정도에 따라 직렬화 지점을 다르게 두는 것이 이 등급의 목적이다.
 *
 * <ul>
 *   <li>{@link #NORMAL} — 재고 row 하나를 조건부 UPDATE로 깎는다. 직렬화 지점이 그 row
 *       하나이지만, 주문이 수천 개 옵션에 흩어지는 평시에는 옵션당 초당 몇 건이라 문제가
 *       되지 않는다. 가장 단순하고 요청당 DB 작업도 가장 적다.</li>
 *   <li>{@link #POPULAR} — 재고를 N개 샤드로 쪼개고 그중 하나를 깎는다. 기획전·타임세일처럼
 *       옵션 수십 개에 주문이 몰릴 때 단일 row 직렬화를 1/N로 낮춘다. 대신 샤드별 잔량이
 *       불균등해져 마지막 재고를 못 파는 구간이 생기므로 재조정이 필요하다.</li>
 *   <li>{@link #HOT} — 재고 1개당 row 1줄로 쪼개고 {@code SELECT ... FOR UPDATE SKIP LOCKED}로
 *       확보한다. 선착순처럼 단일 옵션에 트래픽 전량이 몰릴 때만 값을 한다. 요청당 DB 작업이
 *       가장 많은 대신(잠금 스캔 + row UPDATE + 보조 인덱스 갱신) 경합이 사실상 사라진다.</li>
 * </ul>
 *
 * <p>기본값은 {@link #NORMAL}이다. 상위 등급은 경합이 실제로 관측된 옵션에만 올린다 —
 * 경합이 없는데 등급을 올리면 요청당 비용만 늘어난다.
 */
public enum StockContention {

    /** 단일 재고 row + 조건부 원자 갱신. 평시 기본값. */
    NORMAL,

    /** 재고를 N샤드로 분할하고 임의 샤드를 원자 갱신. 기획전·타임세일. */
    POPULAR,

    /** 재고 1개당 row + SKIP LOCKED. 선착순·한정판. */
    HOT
}
